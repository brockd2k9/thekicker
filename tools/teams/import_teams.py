#!/usr/bin/env python3
"""Team data import: data/teams/source/*.csv -> data/teams/{high_school,college,pro}.json

The game loads teams only from data/teams/*.json (TeamDatabase autoload).
Those files are generated: edit the CSVs in data/teams/source/ (format:
DATA_FORMAT.md), then run

    python3 tools/teams/import_teams.py
    godot --headless --path . res://tools/validate_teams.tscn      # the validator

Which level a CSV belongs to comes from its file name: high_school_*.csv,
college_*.csv, pro_*.csv (or a "Level" column). Column names are matched
loosely ("Minimum GPA", "min_gpa" and "MinimumGPA" are the same), so the D2
roster CSV imports as it came. Unknown columns are kept under "extra".

What the importer fills in (only when the CSV leaves it blank):
  ID            from the school (college / high school) or club name: lowercase
                words joined by "_" ("Hoboken High School" -> hoboken_high_school).
                Give IDs explicitly once a team is in use: saves refer to them.
  Abbreviation  2-4 letters, unique within the level (DATA_FORMAT.md, "Abbreviations").
  Nickname      the "Team" column minus a leading town word ("Burlington
                Timberhawks" in Burlington -> "Timberhawks").
  Colors        "School Colors", else the home jersey and home pants.
  Rival         the rival's id, when the "Rival" name matches a school.
And it cleans one known data defect (clean_stadium): stadium names that
repeat the town ("Burlington Burlington Timberhawks Field" -> "Burlington
Timberhawks Field"). Every change, every name it wasn't sure about (left as
it was), and every "Team" column cut short for a two-word town go to
data/teams/import_report.md for review.
It never invents ratings: missing numbers stay missing (TeamDatabase uses
documented defaults and the validator lists them).
"""

import argparse
import csv
import glob
import json
import os
import re
import sys

LEVELS = ("high_school", "college", "pro")
OUT_DOC = ("Generated by tools/teams/import_teams.py from data/teams/source/*.csv. Edit the CSVs, "
           "not this file. Field reference: DATA_FORMAT.md.")

# Normalized header -> schema field.
ALIASES = {
    "id": "id", "teamid": "id",
    "level": "level",
    "division": "division", "classification": "division",
    "region": "region",
    "conference": "conference",
    "league": "league",
    "school": "name", "name": "name", "club": "name",
    "city": "city", "town": "city", "towncommunity": "city", "market": "city",
    "state": "state",
    "county": "county",
    "team": "team", "teamname": "team",
    "nickname": "nickname",
    "mascot": "mascot",
    "abbreviation": "abbr", "abbr": "abbr", "short": "abbr",
    "stadium": "stadium", "capacity": "capacity", "stadiumcapacity": "capacity",
    "crowdnoise": "crowd_noise", "prestige": "prestige", "draftrating": "draft_rating",
    "recruitingpoints": "recruiting_points", "minimumrecruitingpoints": "recruiting_points",
    "minimumplayerovr": "min_ovr", "minovr": "min_ovr", "minimumovr": "min_ovr",
    "minimumgpa": "min_gpa", "mingpa": "min_gpa",
    "nationalchampionships": "national_titles", "nationaltitles": "national_titles",
    "conferencechampionships": "conference_titles", "conferencetitles": "conference_titles",
    "bowlwins": "bowl_wins",
    "schoolcolors": "colors", "colors": "colors", "teamcolors": "colors",
    "homejersey": "home_jersey", "homepants": "home_pants", "homehelmet": "home_helmet",
    "awayjersey": "away_jersey", "awaypants": "away_pants", "awayhelmet": "away_helmet",
    "rival": "rival", "primaryrival": "rival", "rivalrytrophy": "rivalry_trophy",
    "fanbase": "fan_base",
    "franchisehistory": "franchise_history", "franchiserecord": "franchise_history",
    "teamidentity": "identity", "identity": "identity",
    "strength": "strength", "rating": "strength", "teamrating": "strength",
    "placeholder": "placeholder",
    "notes": "notes",
}
INTS = ("capacity", "crowd_noise", "prestige", "draft_rating", "fan_base", "recruiting_points", "min_ovr",
        "national_titles", "conference_titles", "bowl_wins", "strength")
FLOATS = ("min_gpa",)
# Pro markets with more than one club (set per run by main()).
SHARED_MARKETS = set()
# Collected while importing, written to REPORT_FILE: (row, before, after, why).
REPORT = {"changed": [], "unsure": [], "cut_short": []}
REPORT_FILE = "import_report.md"
# Words left out of generated abbreviations.
FILLER = {"of", "the", "at", "and", "&"}


def norm_header(h):
    return re.sub(r"[^a-z0-9]", "", h.lower())


def slug(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def title(s):
    return " ".join(w[:1].upper() + w[1:] for w in s.strip().split())


def level_of(path, row):
    lv = slug(row.get("level", ""))
    if lv in LEVELS:
        return lv
    base = os.path.basename(path)
    for lv in LEVELS:
        if base.startswith(lv):
            return lv
    return ""


def number(v, kind):
    v = v.strip().replace(",", "")
    if v == "" or v.upper() in ("N/A", "NA", "-"):
        return None
    try:
        return float(v) if kind is float else int(float(v))
    except ValueError:
        return None


def nickname(team, city):
    """'Burlington Timberhawks' in Burlington -> 'Timberhawks'; 'New York Guardians' in
    New York -> 'Guardians'; 'New Redtails' in New Bedford (cut short) -> 'Redtails';
    'Foxes' -> 'Foxes'."""
    team = team.strip()
    if not team:
        return ""
    if city and team.lower().startswith(city.lower() + " "):
        return team[len(city) + 1:].strip()  # "New York Guardians" -> "Guardians"
    first = city.split()[0] if city.split() else ""
    if first and team.startswith(first + " "):
        return team[len(first) + 1:].strip()
    return team


def words(s):
    return s.split()


def clean_stadium(stadium, city, team):
    """Removes a repeated town from a stadium name, judged per row.

    Returns (name, status, reason): status "changed" (name is the clean one),
    "unsure" (a word repeats but not in a known pattern: name is unchanged,
    for review) or "" (nothing to do).

      town twice in a row     "Burlington Burlington Timberhawks Field" (Burlington)
                              -> "Burlington Timberhawks Field"
      town + cut-short Team   "New Bedford New Redtails Field" (New Bedford, Team
                              "New Redtails": the town's first word + nickname)
                              -> "New Bedford Redtails Field"
    """
    w, cw = words(stadium), words(city)
    if not w or not cw:
        return stadium, "", ""
    n = len(cw)
    low = [x.lower() for x in w]
    clow = [x.lower() for x in cw]
    # The whole town, twice in a row at the start.
    if low[:n] == clow and low[n:2 * n] == clow:
        return " ".join(w[n:]), "changed", "town repeated (%s %s)" % (city, city)
    # Town, then the "Team" column whose town was cut to its first word.
    tw = words(team)
    if n >= 2 and low[:n] == clow and len(tw) >= 2 and tw[0].lower() == clow[0] \
            and [x.lower() for x in tw[1:n]] != clow[1:] \
            and low[n:n + len(tw)] == [x.lower() for x in tw]:
        return " ".join(w[:n] + w[n + 1:]), "changed", \
            "town + cut-short Team column (%s %s)" % (city, team)
    # Any other repeated word: leave it, but list it.
    seen = {}
    for x in low:
        if len(x) > 2 and x.isalpha() or x.endswith("."):
            seen[x] = seen.get(x, 0) + 1
    rep = [x for x, k in seen.items() if k > 1]
    if rep:
        return stadium, "unsure", "repeats %s; not a known town pattern" % ", ".join("'%s'" % r for r in rep)
    return stadium, "", ""


def cut_short_team(team, city):
    """True when the "Team" column holds only the first word of a multi-word
    town plus the nickname ("New Redtails" for New Bedford)."""
    tw, cw = words(team), words(city)
    return len(cw) >= 2 and len(tw) >= 2 and tw[0].lower() == cw[0].lower() \
        and [x.lower() for x in tw[1:len(cw)]] != [x.lower() for x in cw[1:]]


def make_abbr(name, city, taken, level=""):
    """2-4 letters, unique in `taken`. College / pro: initials of the name (minus
    filler words), else town letters. High school: the town's first letters
    ("Hoboken" -> HOB). A numbered fallback if everything is taken."""
    words = [w for w in re.findall(r"[A-Za-z]+", name) if w.lower() not in FILLER]
    cands = []
    if level == "pro" and city:
        # The market: BUF, KC; a market with two clubs adds the nickname's
        # first letter (NYG, NYE). SHARED_MARKETS is set by main().
        town = re.findall(r"[A-Za-z]+", city)
        base = town[0][:3].upper() if len(town) == 1 else "".join(w[0] for w in town).upper()
        nick = [w for w in re.findall(r"[A-Za-z]+", name) if w.lower() not in [x.lower() for x in town]]
        with_nick = (base + nick[0][0].upper())[:4] if nick else base
        if city.lower() in SHARED_MARKETS:
            cands.append(with_nick)
        cands += [base, with_nick]
    if level == "high_school":
        town = re.findall(r"[A-Za-z]+", city or name)
        if town:
            cands.append(town[0][:3].upper())
            if len(town) >= 2:
                cands.append((town[0][:2] + town[1][:1]).upper())
    if len(words) >= 2 and level != "high_school":
        init = "".join(w[0] for w in words)[:4].upper()
        cands.append(init)
    town = re.findall(r"[A-Za-z]+", city or name)
    if town:
        cands.append(town[0][:3].upper())
        if len(town) >= 2:
            cands.append((town[0][:2] + town[1][:1]).upper())
            cands.append((town[0][:1] + town[1][:2]).upper())
        cands.append(town[0][:4].upper())
    if words:
        cands.append((words[0][:2] + words[-1][:1]).upper())
    for c in cands:
        if 2 <= len(c) <= 4 and c not in taken:
            return c
    base = (cands[0] if cands else "TM")[:3]
    n = 2
    while "%s%d" % (base, n) in taken:
        n += 1
    return "%s%d" % (base, n)


def read_rows(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        reader = csv.reader(f)
        try:
            header = next(reader)
        except StopIteration:
            return []
        keys = []
        for h in header:
            k = ALIASES.get(norm_header(h))
            keys.append(k if k else "extra:" + h.strip())
        rows = []
        for n, raw in enumerate(reader, start=2):
            if not any(c.strip() for c in raw):
                continue
            row = {"_file": os.path.basename(path), "_line": n}
            for k, v in zip(keys, raw):
                if k and v.strip() != "":
                    row[k] = v.strip()
            rows.append(row)
        return rows


def to_team(row, level):
    t = {"id": row.get("id", ""), "level": level, "name": row.get("name", "") or row.get("team", "")}
    city = row.get("city", "")
    t["nickname"] = row.get("nickname", "") or nickname(row.get("team", ""), city)
    if not row.get("nickname") and cut_short_team(row.get("team", ""), city):
        REPORT["cut_short"].append((row, row.get("team", ""), t["nickname"], ""))
    for k in ("mascot", "abbr", "city", "state", "county", "region", "division", "conference", "league",
              "identity", "notes"):
        if row.get(k):
            t[k] = row[k]
    # Pro guides group teams as Conference (AFC) > Division (AFC East). In the
    # team data the group a team plays in is always "conference" and the
    # group above it "division", so those two swap.
    if level == "pro" and t.get("division") and t.get("conference") \
            and t["division"].lower().startswith(t["conference"].lower() + " "):
        t["division"], t["conference"] = t["conference"], t["division"]
    if level == "high_school" and not t.get("division"):
        t["division"] = "HS"
    if t.get("division"):
        t["division"] = t["division"].upper()
    # Colors: "School Colors", else the home uniform.
    if row.get("colors"):
        t["colors"] = [title(c) if not c.strip().startswith("#") else c.strip()
                       for c in row["colors"].split(",") if c.strip()]
    elif row.get("home_jersey"):
        cols = [title(row["home_jersey"])]
        second = row.get("home_pants") or row.get("away_jersey") or ""
        if second and title(second) != cols[0]:
            cols.append(title(second))
        elif row.get("away_pants") and title(row["away_pants"]) != cols[0]:
            cols.append(title(row["away_pants"]))
        t["colors"] = cols
    uni = {}
    for side in ("home", "away"):
        u = {part: title(row[side + "_" + part]) for part in ("jersey", "pants", "helmet") if row.get(side + "_" + part)}
        if u:
            uni[side] = u
    if uni:
        t["uniforms"] = uni
    if row.get("stadium") or row.get("capacity"):
        st, status, why = clean_stadium(row.get("stadium", ""), city, row.get("team", ""))
        if status:
            REPORT[status].append((row, row.get("stadium", ""), st, why))
        t["stadium"] = {"name": st}
        cap = number(row.get("capacity", ""), int)
        if cap is not None:
            t["stadium"]["capacity"] = cap
    ratings = {k: number(row[k], int) for k in ("prestige", "crowd_noise", "draft_rating", "fan_base") if row.get(k)}
    ratings = {k: v for k, v in ratings.items() if v is not None}
    if ratings:
        t["ratings"] = ratings
    rec = {}
    if row.get("recruiting_points"):
        rec["points"] = number(row["recruiting_points"], int)
    if row.get("min_ovr"):
        rec["min_ovr"] = number(row["min_ovr"], int)
    if row.get("min_gpa"):
        rec["min_gpa"] = number(row["min_gpa"], float)
    rec = {k: v for k, v in rec.items() if v is not None}
    if rec:
        t["recruiting"] = rec
    hist = {k: number(row[k], int) for k in ("national_titles", "conference_titles", "bowl_wins") if row.get(k)}
    hist = {k: v for k, v in hist.items() if v is not None}
    if row.get("franchise_history"):
        # "AFC Championship 2; League Titles 1"
        fh = row["franchise_history"]
        m = re.search(r"Championships? (\d+)", fh)
        if m and "conference_titles" not in hist:
            hist["conference_titles"] = int(m.group(1))
        m = re.search(r"League Titles? (\d+)", fh, re.I)
        if m:
            hist["league_titles"] = int(m.group(1))
        hist["summary"] = fh
    if hist:
        t["history"] = hist
    if row.get("rival"):
        t["rival"] = {"name": row["rival"]}
        if row.get("rivalry_trophy"):
            t["rival"]["trophy"] = row["rivalry_trophy"]
    s = number(row.get("strength", ""), int)
    if s is not None:
        t["strength"] = s
    if row.get("placeholder", "").strip().lower() in ("yes", "y", "true", "1", "x"):
        t["placeholder"] = True
    extra = {k[6:]: v for k, v in row.items() if k.startswith("extra:")}
    if extra:
        t["extra"] = extra
    t["_src"] = "%s:%d" % (row["_file"], row["_line"])
    return t


def write_report(path, teams):
    """data/teams/import_report.md: what the importer changed or wants checked."""
    nick_users = {}
    for lv in LEVELS:
        for t in teams[lv]:
            nick_users.setdefault(t.get("nickname", "").lower(), []).append(t["name"])

    def where(row):
        return "%s:%d" % (row["_file"], row["_line"])

    out = ["# Team import report", "",
           "Generated by tools/teams/import_teams.py on every run. The source CSVs are not changed;",
           "the fixes below are applied to data/teams/*.json.", ""]
    ch = REPORT["changed"]
    out += ["## Stadium names cleaned (%d)" % len(ch), "",
            "The town was repeated at the start of the name. Detected per row (clean_stadium).", "",
            "| Row | School | Before | After | Why |", "|---|---|---|---|---|"]
    out += ["| %s | %s | %s | %s | %s |" % (where(r), r.get("name", ""), b, a, w) for r, b, a, w in ch]
    un = REPORT["unsure"]
    out += ["", "## Stadium names left as they were: please check (%d)" % len(un), "",
            "A word repeats, but not in the town pattern above, so the name may be intended.", "",
            "| Row | School | City | Stadium | Why |", "|---|---|---|---|---|"]
    out += ["| %s | %s | %s | %s | %s |" % (where(r), r.get("name", ""), r.get("city", ""), b, w) for r, b, a, w in un]
    cs = REPORT["cut_short"]
    out += ["", "## Team column cut short for multi-word towns (%d)" % len(cs), "",
            "The \"Team\" column holds the town's first word + the nickname (\"New Redtails\" for New",
            "Bedford). The nickname used is the Team column without that word. \"Also used by\" lists",
            "other teams with the same nickname: evidence the word is a real nickname.", "",
            "| Row | School | City | Team column | Nickname used | Also used by |", "|---|---|---|---|---|---|"]
    for r, b, a, w in cs:
        others = [n for n in nick_users.get(a.lower(), []) if n != r.get("name", "")]
        out.append("| %s | %s | %s | %s | %s | %s |" % (where(r), r.get("name", ""), r.get("city", ""), b, a,
                                                       ", ".join(others[:3]) + (" ..." if len(others) > 3 else "") or "-"))
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s (%d stadium names cleaned, %d to check, %d cut-short Team columns)"
          % (path, len(ch), len(un), len(cs)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default="data/teams/source")
    ap.add_argument("--out", default="data/teams")
    a = ap.parse_args()
    paths = sorted(glob.glob(os.path.join(a.source, "*.csv")))
    if not paths:
        print("No CSV files in %s" % a.source)
        return 1
    teams = {lv: [] for lv in LEVELS}
    for k in REPORT:
        REPORT[k].clear()
    problems = []
    for p in paths:
        for row in read_rows(p):
            lv = level_of(p, row)
            if not lv:
                problems.append("%s:%d: can't tell the level (file name should start with high_school_, "
                                "college_ or pro_, or add a Level column)" % (row["_file"], row["_line"]))
                continue
            teams[lv].append(to_team(row, lv))
    # IDs, then abbreviations (unique per level), then rivals (by name -> id).
    by_name = {}
    for lv in LEVELS:
        for t in teams[lv]:
            if not t["id"]:
                t["id"] = slug(t["name"])
            by_name.setdefault(t["name"].lower(), t["id"])
    SHARED_MARKETS.clear()
    markets = {}
    for t in teams["pro"]:
        markets[t.get("city", "").lower()] = markets.get(t.get("city", "").lower(), 0) + 1
    SHARED_MARKETS.update(m for m, n in markets.items() if m and n > 1)
    for lv in LEVELS:
        taken = set(t["abbr"].upper() for t in teams[lv] if t.get("abbr"))
        for t in teams[lv]:
            if not t.get("abbr"):
                t["abbr"] = make_abbr(t["name"], t.get("city", ""), taken, lv)
                taken.add(t["abbr"])
            t["abbr"] = t["abbr"].upper()
        for t in teams[lv]:
            r = t.get("rival")
            if r and r.get("name", "").lower() in by_name:
                r["id"] = by_name[r["name"].lower()]
    for lv in LEVELS:
        lst = sorted(teams[lv], key=lambda t: (t.get("division", ""), t.get("conference", ""), t["name"]))
        for t in lst:
            t.pop("_src", None)
        out = {"_doc": OUT_DOC, "level": lv, "teams": lst}
        path = os.path.join(a.out, lv + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(out, f, indent=1, ensure_ascii=False)
            f.write("\n")
        print("wrote %s (%d teams)" % (path, len(lst)))
    write_report(os.path.join(a.out, REPORT_FILE), teams)
    for p in problems:
        print("ERROR " + p)
    print("Next: godot --headless --path . res://tools/validate_teams.tscn  (checks the imported data)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
